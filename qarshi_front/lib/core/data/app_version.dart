/// Версия сборки для диагностики.
///
/// Нужна из-за кэша: Telegram и браузер могут держать старую сборку, когда на
/// сервере уже лежит новая. По этой строке в меню сразу видно, что реально
/// открыто у пользователя, и не приходится сверять хэши файлов вручную.
///
/// Значения подставляются при сборке через --dart-define (см. scripts в корне
/// qarshi_front). При обычном `flutter run` остаются значения по умолчанию.
const String appVersion = String.fromEnvironment(
  'APP_VERSION',
  defaultValue: '1.0.0',
);

/// Идентификатор конкретной сборки: короткий хэш коммита и время сборки.
/// Меняется при каждой выкладке, поэтому по нему видно, свежая версия или нет.
const String appBuild = String.fromEnvironment(
  'APP_BUILD',
  defaultValue: 'dev',
);

/// Готовая строка для показа в интерфейсе.
String get appVersionLabel => 'Версия $appVersion · $appBuild';
